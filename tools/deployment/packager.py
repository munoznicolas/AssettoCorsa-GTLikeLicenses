"""
build_cm_package.py
Assetto Corsa Content Manager (CM) Distribution Packaging Tool

Bundles the repository into a Content Manager compatible drag-and-drop zip archive
at release/AssettoCorsa_GT_Licenses.zip according to docs/07_directory_structure_and_packaging_spec.md.

Archive Topology:
  extension/
    lua/
      new-modes/
        gt-license/
          manifest.ini
          scenario.lua
          engine/
            gt_license_engine.lua
            gt_physics_hooks.lua
            gt_adjudicator.lua
            gt_session_reset.lua
          ui/
            license_hud.lua
            render_gates.lua
            audio_manager.lua
          data/
            tests/
              national_b/
              national_a/
              international_b/
              international_a/
              super_license/
          assets/
            audio/
            textures/
  content/
    career/
      series_gt_license_b/
      series_gt_license_a/
      series_gt_license_ib/
      series_gt_license_ia/
      series_gt_license_s/
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from typing import Dict, List, Optional, Tuple

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_OUTPUT_ZIP = os.path.join(REPO_ROOT, "release", "AssettoCorsa_GT_Licenses.zip")

DEFAULT_MANIFEST_INI = """[ABOUT]
NAME = Gran Turismo Licenses
AUTHOR = Assetto Corsa GT-Like Licenses Team
VERSION = {version}
DESCRIPTION = Gran Turismo style driving school licenses, sector tests, and graduation hot laps.

[RULES]
BASE_MODE = PRACTICE
PENALTIES = 1
START_TYPE = PIT

[TWEAKS]
IMMEDIATE_START = 1
DISABLE_FLAGS = YELLOW, BLUE
HIDE_PITCREW = 1
ASSOCIATED_APPS = gt_license
"""

DEFAULT_SCENARIO_LUA = """-- ==============================================================================
-- Gran Turismo Licenses - Master CSP Scenario Entry Point
-- Generated by Assetto Corsa GT Licenses Builder
-- ==============================================================================

local engine = require("engine/license_engine")
require("ui/license_hud")
require("ui/render_gates")
require("ui/audio_manager")

return engine
"""


class CMPackageBuilder:
    """Builds and packages the mod into a Content Manager drag-and-drop ZIP archive."""

    def __init__(
        self,
        repo_root: str = REPO_ROOT,
        output_zip: str = DEFAULT_OUTPUT_ZIP,
        version: str = "1.0.0",
        verbose: bool = False,
        dry_run: bool = False,
    ):
        self.repo_root = repo_root
        self.output_zip = output_zip
        self.version = version
        self.verbose = verbose
        self.dry_run = dry_run
        self.entries: List[Tuple[str, str]] = []  # (source_abs_or_synthetic, zip_arcname)
        self.synthetic_files: Dict[str, str] = {}  # zip_arcname -> content_str

    def stage_files(self) -> None:
        """Determines the full mapping of source files to in-archive paths."""
        self.entries.clear()
        self.synthetic_files.clear()

        gt_mode_base = "extension/lua/new-modes/gt-license"

        # 1. Manifest and Scenario / Mode scripts
        lua_manifest = os.path.join(self.repo_root, "lua", "manifest.ini")
        if os.path.isfile(lua_manifest):
            self.entries.append((lua_manifest, f"{gt_mode_base}/manifest.ini"))
        else:
            self.synthetic_files[f"{gt_mode_base}/manifest.ini"] = (
                DEFAULT_MANIFEST_INI.format(version=self.version)
            )

        lua_scenario = os.path.join(self.repo_root, "lua", "scenario.lua")
        if os.path.isfile(lua_scenario):
            self.entries.append((lua_scenario, f"{gt_mode_base}/scenario.lua"))
            self.entries.append((lua_scenario, f"{gt_mode_base}/mode.lua"))
        else:
            self.synthetic_files[f"{gt_mode_base}/scenario.lua"] = DEFAULT_SCENARIO_LUA
            self.synthetic_files[f"{gt_mode_base}/mode.lua"] = DEFAULT_SCENARIO_LUA

        # 2. Lua Engine scripts
        engine_src = os.path.join(self.repo_root, "lua", "engine")
        if os.path.isdir(engine_src):
            self._add_directory_tree(engine_src, f"{gt_mode_base}/engine")

        # 3. Lua UI scripts
        ui_src = os.path.join(self.repo_root, "lua", "ui")
        if os.path.isdir(ui_src):
            self._add_directory_tree(ui_src, f"{gt_mode_base}/ui")

        # 4. Content Tests (58 Test JSON files)
        tests_src = os.path.join(self.repo_root, "content", "tests")
        if os.path.isdir(tests_src):
            self._add_directory_tree(tests_src, f"{gt_mode_base}/data/tests")

        # 5. Media Assets (Audio & Textures)
        audio_src = os.path.join(self.repo_root, "assets", "audio")
        if os.path.isdir(audio_src):
            self._add_directory_tree(audio_src, f"{gt_mode_base}/assets/audio")

        textures_src = os.path.join(self.repo_root, "assets", "textures")
        if os.path.isdir(textures_src):
            self._add_directory_tree(textures_src, f"{gt_mode_base}/assets/textures")

        # 6. Content Manager Career Series
        career_src = os.path.join(self.repo_root, "content", "career")
        if os.path.isdir(career_src):
            self._add_directory_tree(career_src, "content/career")

        # 7. Assetto Corsa Lua UI Apps (Movable GT License HUD App)
        app_src = os.path.join(self.repo_root, "apps", "lua", "gt_license")
        if os.path.isdir(app_src):
            self._add_directory_tree(app_src, "apps/lua/gt_license")

        # 8. Optional Root Documentation
        readme_src = os.path.join(self.repo_root, "README.md")
        if os.path.isfile(readme_src):
            self.entries.append((readme_src, f"{gt_mode_base}/README.md"))

    def _add_directory_tree(self, source_dir: str, dest_prefix: str) -> None:
        """Recursively registers all files in source_dir under dest_prefix."""
        for root, _, filenames in os.walk(source_dir):
            for fname in sorted(filenames):
                # Skip version control, temporary or hidden files
                if fname.startswith(".") or fname.endswith(".tmp") or fname.endswith(".pyc"):
                    continue
                full_path = os.path.join(root, fname)
                rel_path = os.path.relpath(full_path, source_dir).replace("\\", "/")
                arcname = f"{dest_prefix}/{rel_path}"
                self.entries.append((full_path, arcname))

    def build_package(self) -> bool:
        """Constructs the ZIP archive."""
        self.stage_files()

        total_files = len(self.entries) + len(self.synthetic_files)
        if total_files == 0:
            print("[ERROR] No files found to package.", file=sys.stderr)
            return False

        print(f"Staged {total_files} file(s) for packaging.")

        if self.dry_run:
            print("[DRY-RUN] Files to be packaged:")
            for src, arc in sorted(self.entries, key=lambda x: x[1]):
                size = os.path.getsize(src)
                print(f"  + {arc} ({size:,} bytes) <- {os.path.relpath(src, self.repo_root)}")
            for arc, content in sorted(self.synthetic_files.items()):
                print(f"  * {arc} ({len(content):,} bytes) [generated]")
            print(f"[DRY-RUN] Package would be written to: {self.output_zip}")
            return True

        # Ensure output directory exists
        out_dir = os.path.dirname(os.path.abspath(self.output_zip))
        os.makedirs(out_dir, exist_ok=True)

        # Temporary file while writing to avoid partially written zip archives
        temp_zip = os.path.join(out_dir, f".tmp_{os.path.basename(self.output_zip)}")
        if os.path.isfile(temp_zip):
            os.remove(temp_zip)

        total_uncompressed = 0
        try:
            with zipfile.ZipFile(temp_zip, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
                # Add real files
                for src_path, arcname in sorted(self.entries, key=lambda x: x[1]):
                    zf.write(src_path, arcname)
                    size = os.path.getsize(src_path)
                    total_uncompressed += size
                    if self.verbose:
                        print(f"  Packed: {arcname} ({size:,} bytes)")

                # Add generated files
                for arcname, content in sorted(self.synthetic_files.items()):
                    zf.writestr(arcname, content)
                    total_uncompressed += len(content.encode("utf-8"))
                    if self.verbose:
                        print(f"  Generated & Packed: {arcname}")

            # Atomically move temporary zip to target path
            if os.path.isfile(self.output_zip):
                os.remove(self.output_zip)
            os.replace(temp_zip, self.output_zip)

        except Exception as e:
            if os.path.isfile(temp_zip):
                try:
                    os.remove(temp_zip)
                except Exception:
                    pass
            print(f"[ERROR] Failed to create package: {e}", file=sys.stderr)
            return False

        compressed_size = os.path.getsize(self.output_zip)
        ratio = (compressed_size / total_uncompressed * 100.0) if total_uncompressed > 0 else 0.0

        print("=" * 80)
        print(" ASSETTO CORSA GT LICENSES - CONTENT MANAGER PACKAGE BUILT")
        print("=" * 80)
        print(f"Destination:          {self.output_zip}")
        print(f"Total Files Packed:   {total_files}")
        print(f"Uncompressed Size:    {total_uncompressed:,} bytes ({total_uncompressed / 1024 / 1024:.2f} MB)")
        print(f"Compressed Size:      {compressed_size:,} bytes ({compressed_size / 1024 / 1024:.2f} MB)")
        print(f"Compression Ratio:    {ratio:.1f}%")
        print("Content Manager Drag & Drop Ready: YES")
        print("=" * 80)

        return True


def run_pre_validation() -> bool:
    """Executes tools/validate_curriculum.py before packaging."""
    val_script = os.path.join(REPO_ROOT, "tools", "validate_curriculum.py")
    if not os.path.isfile(val_script):
        print(f"[WARN] Validation script {val_script} not found, skipping pre-validation.")
        return True

    print("[PRE-VALIDATION] Running curriculum validator...")
    res = subprocess.run([sys.executable, val_script, "--all"], capture_output=True, text=True)
    print(res.stdout)
    if res.returncode != 0:
        print("[ERROR] Curriculum validation failed! Package creation aborted.", file=sys.stderr)
        return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Assetto Corsa GT Licenses - Content Manager Distribution Packager"
    )
    parser.add_argument(
        "--output", "-o",
        type=str,
        default=DEFAULT_OUTPUT_ZIP,
        help=f"Path to destination ZIP archive (default: {DEFAULT_OUTPUT_ZIP})"
    )
    parser.add_argument(
        "--version",
        type=str,
        default="1.0.0",
        help="Package version string (default: 1.0.0)"
    )
    parser.add_argument(
        "--validate",
        action="store_true",
        help="Execute tools/validate_curriculum.py before packaging and abort on errors"
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Display staged files without writing the ZIP archive"
    )
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Print verbose file staging and packaging output"
    )

    args = parser.parse_args()

    if args.validate:
        if not run_pre_validation():
            return 1

    builder = CMPackageBuilder(
        repo_root=REPO_ROOT,
        output_zip=args.output,
        version=args.version,
        verbose=args.verbose,
        dry_run=args.dry_run,
    )

    success = builder.build_package()
    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
