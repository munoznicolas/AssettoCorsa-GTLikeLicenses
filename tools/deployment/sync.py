#!/usr/bin/env python3
"""
sync_to_ac.py
Assetto Corsa Live Directory Auto-Sync Tool

Synchronizes repository files (Lua engine, UI scripts, test definitions, assets, career series)
directly into the local Assetto Corsa installation directory (e.g. D:\\SteamLibrary\\steamapps\\common\\assettocorsa).

Usage:
  python tools/sync_to_ac.py [--ac-root PATH] [--dry-run]
"""

import argparse
import os
import shutil
import sys
from typing import List, Tuple

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_AC_ROOT = r"D:\SteamLibrary\steamapps\common\assettocorsa"

DEFAULT_MANIFEST_INI = """[ABOUT]
NAME = Gran Turismo Licenses
AUTHOR = Assetto Corsa GT-Like Licenses Team
VERSION = 1.0.0
DESCRIPTION = Gran Turismo style driving school licenses, sector tests, and graduation hot laps.

[RULES]
BASE_MODE = PRACTICE
PENALTIES = 1
START_TYPE = PIT

[TWEAKS]
IMMEDIATE_START = 1
DISABLE_FLAGS = YELLOW, BLUE
HIDE_PITCREW = 1
"""

DEFAULT_SCENARIO_LUA = """-- ==============================================================================
-- Gran Turismo Licenses - Master CSP Scenario Entry Point
-- Generated by Assetto Corsa GT Licenses Sync Tool
-- ==============================================================================

local engine = require("engine/gt_license_engine")
require("ui/gt_license_hud")
require("ui/gt_render_gates")
require("ui/gt_render_ghost")
require("ui/gt_audio_manager")

return engine
"""


def build_sync_mappings(repo_root: str, ac_root: str) -> List[Tuple[str, str]]:
    """Generates source file to target AC file path mappings."""
    mappings: List[Tuple[str, str]] = []
    gt_mode_base = os.path.join(ac_root, "extension", "lua", "new-modes", "gt-license")

    # 1. Lua Engine scripts
    engine_src = os.path.join(repo_root, "lua", "engine")
    if os.path.isdir(engine_src):
        for root, _, files in os.walk(engine_src):
            for f in files:
                if f.endswith(".lua"):
                    src = os.path.join(root, f)
                    rel = os.path.relpath(src, engine_src)
                    dst = os.path.join(gt_mode_base, "engine", rel)
                    mappings.append((src, dst))

    # 2. Lua UI scripts
    ui_src = os.path.join(repo_root, "lua", "ui")
    if os.path.isdir(ui_src):
        for root, _, files in os.walk(ui_src):
            for f in files:
                if f.endswith(".lua"):
                    src = os.path.join(root, f)
                    rel = os.path.relpath(src, ui_src)
                    dst = os.path.join(gt_mode_base, "ui", rel)
                    mappings.append((src, dst))

    # 3. Content Tests (Test JSON files)
    tests_src = os.path.join(repo_root, "content", "tests")
    if os.path.isdir(tests_src):
        for root, _, files in os.walk(tests_src):
            for f in files:
                if f.endswith(".json"):
                    src = os.path.join(root, f)
                    rel = os.path.relpath(src, tests_src)
                    dst = os.path.join(gt_mode_base, "data", "tests", rel)
                    mappings.append((src, dst))

    # 4. Media Assets (Audio, Textures, Fonts)
    assets_src = os.path.join(repo_root, "assets")
    if os.path.isdir(assets_src):
        for root, _, files in os.walk(assets_src):
            for f in files:
                src = os.path.join(root, f)
                rel = os.path.relpath(src, assets_src)
                dst = os.path.join(gt_mode_base, "assets", rel)
                mappings.append((src, dst))
                # Expose fonts directly at mode root (gt_mode_base/fonts) for seamless DWrite font loading
                if "fonts" in root.lower() and f.endswith(".ttf"):
                    dst_root_font = os.path.join(gt_mode_base, "fonts", f)
                    mappings.append((src, dst_root_font))

    # 5. Career Series
    career_src = os.path.join(repo_root, "content", "career")
    if os.path.isdir(career_src):
        for root, _, files in os.walk(career_src):
            for f in files:
                src = os.path.join(root, f)
                rel = os.path.relpath(src, career_src)
                dst = os.path.join(ac_root, "content", "career", rel)
                mappings.append((src, dst))

    return mappings


def main():
    parser = argparse.ArgumentParser(description="Assetto Corsa Live Directory Sync Tool")
    parser.add_argument("--ac-root", default=DEFAULT_AC_ROOT, help="Target Assetto Corsa root installation directory")
    parser.add_argument("--dry-run", action="store_true", help="Print sync actions without performing file copies")
    args = parser.parse_args()

    ac_root = os.path.abspath(args.ac_root)
    print(f"Target Assetto Corsa Root: {ac_root}")

    if not os.path.isdir(ac_root) and not args.dry_run:
        print(f"[WARNING] Target AC root directory does not exist: {ac_root}")
        print("Set --ac-root to your Assetto Corsa installation path or create the folder.")

    gt_mode_base = os.path.join(ac_root, "extension", "lua", "new-modes", "gt-license")
    mappings = build_sync_mappings(REPO_ROOT, ac_root)

    print(f"Found {len(mappings)} file(s) to synchronize.")

    copied_count = 0
    for src, dst in mappings:
        if args.dry_run:
            print(f"[DRY-RUN] Copy {os.path.relpath(src, REPO_ROOT)} -> {dst}")
        else:
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            if os.path.exists(dst):
                try:
                    if os.path.getsize(src) == os.path.getsize(dst) and os.path.getmtime(src) <= os.path.getmtime(dst):
                        continue
                except OSError:
                    pass
            try:
                shutil.copy2(src, dst)
                copied_count += 1
            except OSError as ex:
                if os.path.exists(dst) and os.path.getsize(src) == os.path.getsize(dst):
                    pass
                else:
                    raise

    # Synthesize manifest.ini and scenario.lua if missing
    manifest_dst = os.path.join(gt_mode_base, "manifest.ini")
    scenario_dst = os.path.join(gt_mode_base, "scenario.lua")
    mode_dst = os.path.join(gt_mode_base, "mode.lua")

    if not args.dry_run:
        os.makedirs(gt_mode_base, exist_ok=True)
        with open(manifest_dst, "w", encoding="utf-8") as f:
            f.write(DEFAULT_MANIFEST_INI)
        with open(scenario_dst, "w", encoding="utf-8") as f:
            f.write(DEFAULT_SCENARIO_LUA)
        with open(mode_dst, "w", encoding="utf-8") as f:
            f.write(DEFAULT_SCENARIO_LUA)
        print(f"[SUCCESS] Synchronized {copied_count} file(s) to Assetto Corsa!")
    else:
        print(f"[DRY-RUN] Would synchronize {len(mappings)} file(s) to {gt_mode_base}.")


if __name__ == "__main__":
    main()
